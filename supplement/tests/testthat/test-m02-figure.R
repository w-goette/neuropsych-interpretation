testthat::test_that("density panels retain the full-law comparison", {
  data <- m02_figure_data()
  testthat::expect_identical(data$summary$rule,c("content","joint"))
  testthat::expect_equal(nrow(data$data),1000L)
  testthat::expect_true(all(is.finite(data$data$density) & data$data$density>=0))
  testthat::expect_equal(unname(data$summary$studies_above_05),c(.05,.3922645970721),tolerance=1e-9)
  testthat::expect_equal(unname(data$summary$mean_fraction),c(.0152303489002,.05),tolerance=1e-9)
  testthat::expect_true(all(data$summary$omitted_lower_plot_mass>=0 & data$summary$omitted_upper_plot_mass>=0))
  testthat::expect_true(all(data$data$density<80))
  plots <- plot_m02_cutoff(data)
  testthat::expect_length(plots,2L)
  testthat::expect_s3_class(plots[[1]],"ggplot")
  testthat::expect_equal(plots[[1]]$scales$get_scales("y")$limits,plots[[2]]$scales$get_scales("y")$limits)
})
