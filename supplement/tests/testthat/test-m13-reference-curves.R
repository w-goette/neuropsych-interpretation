  testthat::expect_equal(sum(fit$grid$posterior_weight), 1, tolerance = 1e-14)
  high <- m13_shape_summary(fit)
  testthat::expect_equal(as.numeric(high[1, 4:13]), as.numeric(d[1, 4:13]), tolerance = 1e-7)
