m13_expect_absolute <- function(actual, expected, tolerance) {
  testthat::expect_equal(length(actual), length(expected))
  testthat::expect_lte(max(abs(unname(actual) - expected)), tolerance)
}
# One assembled example execution serves the cross-target comparisons below.
m13_test_tables <- m13_tables(64L)
testthat::test_that("M13 coupled region/envelope preserves exact geometric identities", {
  post <- m02_posterior(20, 50, 10); region <- m13_joint_region(post)
  m13_expect_absolute(region$coefficient, .5000913807, tolerance = 5.1e-11)
  m13_expect_absolute(c(region$sd_lower, region$sd_upper), c(7.3310122010, 15.4767106558), tolerance = 5.1e-11)
  y <- seq(15, 85, .25); e <- m13_envelope(y, region)
  corners <- expand.grid(sd = c(region$sd_lower, region$sd_upper), sign = c(-1, 1))
  curves <- vapply(seq_len(nrow(corners)), function(i) stats::pnorm((y - (50 + corners$sign[i] * region$coefficient * corners$sd[i])) / corners$sd[i]), numeric(length(y)))
  testthat::expect_equal(e$lower, apply(curves, 1, min), tolerance = 1e-14)
  testthat::expect_equal(e$upper, apply(curves, 1, max), tolerance = 1e-14)
  # Direct variance integration of conditional mean probability: not product substitution.
  mass <- stats::integrate(function(v) (stats::pnorm(region$coefficient * sqrt(20)) - stats::pnorm(-region$coefficient * sqrt(20))) * exp(post$a * log(post$b) - lgamma(post$a) - (post$a + 1) * log(v) - post$b / v), region$sd_lower^2, region$sd_upper^2, rel.tol = 1e-10)$value
  testthat::expect_equal(mass, .95, tolerance = 1e-10)
  p2 <- m02_posterior(2, 0, 1, list(m = 0, kappa = 1, a = 1, b = 100))
  testthat::expect_gt(m13_joint_region(p2)$sd_lower, 1)
  testthat::expect_equal(m13_gamma_expect(function(u) 1, .5), 1, tolerance = 1e-9)
  testthat::expect_equal(m13_gamma_expect(function(u) 1, 9.5), 1, tolerance = 1e-9)
  testthat::expect_error(m13_joint_region(list(m = 0, kappa = 0, a = 1, b = 1)))
  testthat::expect_error(m13_joint_region(post, 1))
})
testthat::test_that("M13 range posterior and transferred intervals retain different meanings", {
  d <- m13_test_tables$range_fraction
  m13_expect_absolute(d$posterior_mean, c(.8404160, .8700579), tolerance = 5.1e-8)
  m13_expect_absolute(d$posterior_median, c(.8499359, .8776121), tolerance = 5.1e-8)
  m13_expect_absolute(d$credible_lower, c(.6803861, .7437029), tolerance = 5.1e-8)
  m13_expect_absolute(d$credible_upper, c(.9472988, .9540208), tolerance = 5.1e-8)
  m13_expect_absolute(d$transferred_lower, c(.3610067, .4922962), tolerance = 5.1e-8)
  m13_expect_absolute(d$transferred_upper, c(.9592537, .9635064), tolerance = 5.1e-8)
  post <- m02_posterior(20, 50, 10)
  for (i in 1:3) testthat::expect_equal(m13_range_cdf(c(d$credible_lower[1], d$posterior_median[1], d$credible_upper[1])[i], post), c(.025, .5, .975)[i], tolerance = 3e-8)
  testthat::expect_equal(m13_range_cdf(0, post), 0)
  testthat::expect_equal(m13_range_cdf(1, post), 1)
  testthat::expect_gt(m13_range_cdf(d$transferred_upper[1], post) - m13_range_cdf(d$transferred_lower[1], post), .95)
  small <- m13_range_bounds(m13_joint_region(post), 50 - 1e-6, 50 + 1e-6)
  testthat::expect_lt(small[2], 1e-6)
  testthat::expect_error(m13_range_mass(0, 0, -1, 1))
  testthat::expect_error(m13_range_cdf(.5, post, 1, -1))
})
testthat::test_that("M13 uniform-error roots use all stationary points and the unchanged fit", {
  for (h in c(0, .3, 2)) for (r in c(.5, 1, 2)) {
    d <- m13_normal_distance(h, r)
    testthat::expect_equal(d, m13_normal_distance(-h, r), tolerance = 1e-13)
    testthat::expect_equal(d, m13_normal_distance(-h / r, 1 / r), tolerance = 1e-13)
    grid <- seq(-15, 15, length.out = 3001)
    testthat::expect_gte(d + 1e-12, max(abs(stats::pnorm(grid) - stats::pnorm((grid - h) / r))))
  }
  testthat::expect_equal(m13_normal_distance(0, 1), 0)
  testthat::expect_equal(m13_normal_distance(.3, 1 + 1e-10), 2 * stats::pnorm(.15) - 1, tolerance = 1e-9)
  testthat::expect_lt(m13_normal_distance(0, 1000), .5)
  testthat::expect_error(m13_normal_distance(0, 0))
  d <- m13_test_tables$fitted_curve_error
  m13_expect_absolute(d$median_error, c(.0820341, .0726255), tolerance = 5.1e-8)
  m13_expect_absolute(d$upper_error_95, c(.1913317, .1638522), tolerance = 5.1e-8)
  m13_expect_absolute(d$probability_error_at_most_point20, c(.9603251, .9853797), tolerance = 5.1e-8)
  post <- m02_posterior(20, 50, 10)
  testthat::expect_equal(m13_error_cdf(d$upper_error_95[1], post), .95, tolerance = 3e-8)
  testthat::expect_equal(m13_error_cdf(.2, post), m13_error_cdf(.2, m02_posterior(20, 7, 3), 7, 3), tolerance = 2e-9)
  testthat::expect_equal(m13_error_cdf(0, post), 0)
  testthat::expect_equal(m13_error_cdf(1, post), 1)
})
testthat::test_that("M13 finite-support refitting and frozen-table posterior stay separate", {
  d <- m13_test_tables
  # Verify both tails by direct binomial probabilities, not beta-call duplication.
  K <- c(1, 3, 7)
  for (i in 1:3) {
    testthat::expect_equal(stats::pbinom(K[i] - 1, 10, d$discrete_cdf$confidence_lower[i], lower.tail = FALSE), .05 / 6, tolerance = 1e-10)
    testthat::expect_equal(stats::pbinom(K[i], 10, d$discrete_cdf$confidence_upper[i]), .05 / 6, tolerance = 1e-10)
  }
  testthat::expect_true(all(d$discrete_cdf$confidence_lower <= d$discrete_cdf$empirical_inclusive))
  testthat::expect_true(all(d$discrete_cdf$confidence_upper >= d$discrete_cdf$empirical_inclusive))
  testthat::expect_equal(nrow(d$discrete_refitting), choose(13, 3))
  testthat::expect_equal(sum(d$discrete_refitting$training_probability), 1, tolerance = 1e-13)
  testthat::expect_equal(d$discrete_refitting_summary$probability_content_at_most_point20, stats::pbinom(2, 10, .3, lower.tail = FALSE), tolerance = 1e-13)
  m13_expect_absolute(d$discrete_refitting_summary$mean_content_across_refitting, .1701736292, tolerance = 5.1e-11)
  testthat::expect_equal(d$discrete_selected_content$posterior_content_mean, 1 / 7, tolerance = 1e-14)
  testthat::expect_equal(c(d$discrete_selected_content$credible_lower, d$discrete_selected_content$credible_upper), stats::qbeta(c(.025, .975), 2, 12), tolerance = 1e-14)
  testthat::expect_equal(sum(d$discrete_quantile$posterior_quantile_mass), 1, tolerance = 1e-14)
  m13_expect_absolute(d$discrete_quantile$posterior_quantile_mass, c(.2336462, .6672232, .0991145, .0000161), tolerance = 5.1e-8)
  testthat::expect_equal(m13_discrete(c(10, 0, 0, 0))$selected$posterior_content_mean, 0)
  testthat::expect_equal(m13_discrete(c(0, 0, 0, 10))$cdf$confidence_lower[1], 0)
  testthat::expect_equal(sum(m13_discrete_refitting(1, c(0, .3, .4, .3))$training_probability), 1, tolerance = 1e-14)
  testthat::expect_error(m13_discrete(c(0, 0)))
  testthat::expect_error(m13_discrete(c(1, 1), c(0, 0)))
  testthat::expect_error(m13_discrete(c(1, 1), prior = c(0, 1)))
})
testthat::test_that("M13 full shape likelihood and conditional regression reproduce the intended targets", {
  d <- m13_test_tables$shape_sensitivity
  m13_expect_absolute(d$posterior_shape_mean, c(1.5094541, 1.8586262), tolerance = 5.1e-8)
  m13_expect_absolute(d$predictive_tail, c(.0875469, .0967499), tolerance = 5.1e-8)
  m13_expect_absolute(d$percentile_lower, c(.0218819, .0242621), tolerance = 5.1e-8)
  m13_expect_absolute(d$percentile_median, c(.0787484, .0873360), tolerance = 5.1e-8)
  m13_expect_absolute(d$percentile_upper, c(.2026291, .2219576), tolerance = 5.1e-8)
  m13_expect_absolute(d$fifth_score_lower, c(16.9922529, 16.5492605), tolerance = 5.1e-8)
  m13_expect_absolute(d$fifth_score_median, c(31.7350874, 30.9434679), tolerance = 5.1e-8)
  m13_expect_absolute(d$fifth_score_upper, c(38.9346568, 38.5136198), tolerance = 5.1e-8)
