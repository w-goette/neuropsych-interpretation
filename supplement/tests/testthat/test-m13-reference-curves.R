  g <- m13_test_tables$transformed_regression
  m13_expect_absolute(g$predictive_tail, .0520031, tolerance = 5.1e-8)
  testthat::expect_equal(g$predictive_tail, g$normal_precision_tail, tolerance = 1e-9)
  testthat::expect_equal(m13_transformed_regression(16, c(0, 0), 50)$predictive_tail, .5, tolerance = 1e-12)
  testthat::expect_error(m13_shape_fit(raw, 0, 2))
  testthat::expect_error(m13_shape_rule(1))
  testthat::expect_error(m13_order_benchmark(c(1, 1)))
})
