  testthat::expect_equal(q$decline_probability, .796877, tolerance = 5e-7)
  testthat::expect_lt(abs(p$negative_new_total_probability - q$negative_new_total_probability), 1e-8)
  testthat::expect_error(m08_item_posterior(rho = 1), "prior")
})
testthat::test_that("causal integration retains both marginals and unlearned assumptions", {
  symmetric <- m08_beta_difference(c(4, 10), c(4, 10))
  testthat::expect_equal(symmetric$mean_effect, 0)
  testthat::expect_equal(symmetric$positive_probability, .5, tolerance = 1e-9)
  testthat::expect_equal(symmetric$lower, -symmetric$upper, tolerance = 1e-9)
  trial <- m08_beta_difference(c(4, 10), c(8, 6))
  testthat::expect_equal(trial$positive_probability, .944649, tolerance = 5e-7)
  low <- m08_benefit(c(8, 2), 80)
  high <- m08_benefit(c(2, 8), 80)
  testthat::expect_lt(low$mean_benefit, high$mean_benefit)
  testthat::expect_error(m08_beta_difference(c(0, 1), c(1, 1)), "Positive")
})

testthat::test_that("M08 figure geometry and readouts encode the stipulated law", {
  data <- m08_figure_data()
  inverse <- solve(matrix(c(100, 80, 80, 100), 2))
  z <- cbind(data$ellipses$first - 50, data$ellipses$retest - 52)
  radius <- rowSums((z %*% inverse) * z)
  testthat::expect_equal(radius, stats::qchisq(data$ellipses$level, 2), tolerance = 1e-12)
  testthat::expect_equal(data$conditional_interval$lower, 40 - stats::qnorm(.975) * 6)
  testthat::expect_equal(data$conditional_interval$upper, 40 + stats::qnorm(.975) * 6)
  testthat::expect_equal(data$readout$expected_retest[2], 40)
  testthat::expect_lt(max(abs(data$readout$marginal_rule_conditional_error - c(.144300, .063820, .038830))), 5e-7)
})
