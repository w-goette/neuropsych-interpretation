testthat::test_that("known reference comparisons keep marginal and conditional laws distinct", {
  x <- m08_joint(35)
  testthat::expect_equal(x$expected_retest, 40)
  testthat::expect_equal(x$standardized_difference, -1 / sqrt(40))
  testthat::expect_equal(x$standardized_innovation, -2 / 3)
  cutoff <- stats::qnorm(.975) * sqrt(40)
  # Integrate the fixed-first-score error under its reference distribution.
  unconditional <- stats::integrate(function(first) m08_joint(first)$marginal_rule_conditional_error * stats::dnorm(first, 50, 10), -Inf, Inf)$value
  testthat::expect_equal(unconditional, .05, tolerance = 1e-9)
  testthat::expect_error(m08_joint(35, alpha = 1), "alpha")
})
testthat::test_that("GLS and proper scale update agree with direct whitening and lm", {
  x <- cbind(1, (0:5) - 2.5); y <- c(51, 47, 46, 44, 41, 41)
  f <- m08_regression(x, y, c(45, 0), diag(c(25, 4)), 3, 2)
  direct <- stats::lm.fit(x, y)
  testthat::expect_equal(f$estimate, unname(direct$coefficients), tolerance = 1e-12)
  testthat::expect_equal(f$residual_quadratic, 4, tolerance = 1e-11)
  testthat::expect_equal(f$posterior_mean[2], -1.971830985915493, tolerance = 1e-11)
  c <- .5^abs(outer(0:5, 0:5, "-"))
  g <- m08_regression(x, y, c(45, 0), diag(c(25, 4)), 3, 2, c)
  whiten <- solve(t(chol(c)))
  independent <- stats::lm.fit(whiten %*% x, drop(whiten %*% y))
  testthat::expect_equal(g$estimate, unname(independent$coefficients), tolerance = 1e-11)
  testthat::expect_equal(g$residual_quadratic, sum(independent$residuals^2), tolerance = 1e-10)
  testthat::expect_equal(g$residual_quadratic, 8.5, tolerance = 1e-10)
  testthat::expect_error(m08_regression(cbind(1, rep(1, 6)), y, c(0, 0), diag(2), 3, 2), "full-rank")
  testthat::expect_error(m08_regression(x, y, c(45, 0), diag(c(1, -1)), 3, 2), "positive definite")
  # A perfectly fitted record has no observed residual scale; do not divide by zero.
  z <- m08_regression(x, drop(x %*% c(45, -2)), c(45, 0), diag(2), 3, 2)
  testthat::expect_true(all(is.infinite(z$coefficient_table$confidence_lower)))
})
testthat::test_that("Gaussian change retains prior and future-error variance separately", {
  p <- m08_normal_update(diag(2), c(50, 42), diag(9, 2), c(50, 50), matrix(c(25, 20, 20, 25), 2))
  d <- c(-1, 1)
  testthat::expect_equal(sum(d * p$mean), -20 / 7, tolerance = 1e-12)
  testthat::expect_equal(drop(crossprod(d, p$covariance %*% d)), 45 / 7, tolerance = 1e-12)
  testthat::expect_error(m08_normal_update(diag(2), c(50, 42), matrix(1, 2, 2), c(50, 50), diag(2)), "positive definite")
})
testthat::test_that("finite count confidence respects floors and conditional coverage", {
  pairs <- expand.grid(first = 0:4, second = 0:4)
  bounds <- dplyr::bind_rows(lapply(seq_len(nrow(pairs)), function(i) m08_conditional_items(pairs$first[i], pairs$second[i])))
  for (h1 in c(-5, -1, 0, 3)) for (h2 in c(-4, 0, 2, 5)) {
    mass <- stats::dbinom(pairs$first, 4, stats::plogis(h1)) * stats::dbinom(pairs$second, 4, stats::plogis(h2))
    testthat::expect_gte(sum(mass * (bounds$lower <= h2 - h1 & bounds$upper >= h2 - h1)), .95 - 1e-12)
  }
  x <- m08_conditional_items(3, 1)
  testthat::expect_equal(x$lower, -6.439739, tolerance = 5e-7)
  testthat::expect_equal(x$upper, 1.552417, tolerance = 5e-7)
  testthat::expect_equal(m08_conditional_items(4, 0)$null_p, 2 / 70, tolerance = 1e-12)
  testthat::expect_equal(m08_conditional_items(0, 0)$lower, -Inf)
  testthat::expect_equal(m08_conditional_items(4, 4)$upper, Inf)
  testthat::expect_equal(m08_binomial_interval(0, 4)[1], c(lower = 0))
  testthat::expect_equal(m08_binomial_interval(4, 4)[2], c(upper = 1))
  testthat::expect_error(m08_conditional_items(5, 0), "count")
})
testthat::test_that("known-item numerical refinement checks different integral representations", {
  p <- m08_item_posterior(1, .5, 32)
  q <- m08_item_posterior(1, .5, 64)
  testthat::expect_equal(p$evidence, p$quadrature_evidence, tolerance = 1e-9)
