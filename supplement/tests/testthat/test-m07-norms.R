# Manuscript decimals imply ABSOLUTE rounding tolerances, not relative errors.
m07_expect_absolute <- function(actual, expected, tolerance = 1e-8) {
  testthat::expect_true(length(actual) == length(expected) && all(abs(as.numeric(actual) - as.numeric(expected)) <= tolerance),
    info = paste("Absolute difference exceeds", tolerance))
}
testthat::test_that("fixed peers, ties, and population mixing keep their targets", {
  m07_expect_absolute(m07_references()$percentile, c(.0668072012688581, .158655253931457, .1127312276001575, .0943616170676378, .142524703701931), tolerance = 2e-7)
  ties <- m07_ties()
  m07_expect_absolute(ties$strict[ties$score == 1], c(.1, .2))
  m07_expect_absolute(ties$inclusive[ties$score == 1], c(.8, .6))
  m07_expect_absolute(ties$midpoint[ties$score == 1], c(.45, .4))
  for (group in 0:1) for (threshold in seq(0, 1, .025)) {
    p <- ties$mass[ties$group == group]; before <- c(0, head(cumsum(p), -1))
    m07_expect_absolute(sum(pmin(p, pmax(0, threshold - before))), threshold, tolerance = 1e-12)
  }
})
testthat::test_that("binomial intervals cover at boundaries and across repeated experiments", {
  m07_expect_absolute(m07_cp(c(0, 4), 4)$lower[1], 0)
  m07_expect_absolute(m07_cp(c(0, 4), 4)$upper[2], 1)
  bounds <- m07_cp(0:12, 12)
  for (p in seq(0, 1, .05)) testthat::expect_gte(sum(stats::dbinom(0:12, 12, p) * (bounds$lower <= p & p <= bounds$upper)), .95 - 1e-12)
  testthat::expect_error(m07_cp(-1, 2)); testthat::expect_error(m07_cp(1, 0)); testthat::expect_error(m07_cp(1, 2, 0))
})
testthat::test_that("anchor assumptions, sign and unlearned offsets remain explicit", {
  known <- m07_anchor_known(); m07_expect_absolute(known$coverage_if_offset_2, .615209, tolerance = 5e-7)
  zero <- m07_anchor(); m07_expect_absolute(unlist(zero[c("confidence_lower", "confidence_upper", "posterior_mean", "posterior_variance", "lower", "upper")], use.names = FALSE),
    c(.80932, 3.19068, 1.834862, .330010, .706704, 2.963021), tolerance = 5e-6)
  positive <- m07_anchor(Gamma = 1); negative <- m07_anchor(-2, 1)
  m07_expect_absolute(negative$posterior_mean, -positive$posterior_mean)
  m07_expect_absolute(negative$lower, -positive$upper, tolerance = 1e-9)
  m07_expect_absolute(negative$upper, -positive$lower, tolerance = 1e-9)
  m07_expect_absolute(positive$posterior_variance - zero$posterior_variance, 1 / 12)
  m07_expect_absolute(positive$confidence_lower, .30932, tolerance = 5e-6)
  testthat::expect_error(m07_anchor(0)); testthat::expect_error(m07_anchor(Gamma = -1))
})
testthat::test_that("selected-only probabilities use the normalization and finite images", {
  fit <- m07_selection()
  m07_expect_absolute(fit$fitted$target_probability, c(.4, .4, .15, .05))
  m07_expect_absolute(fit$inclusion_fraction, .5)
  m07_expect_absolute(nrow(fit$vertices), 12)
  m07_expect_absolute(fit$band$lower, c(.125982, .446885, .769944), tolerance = 5e-7)
  m07_expect_absolute(fit$band$upper, c(.697738, .952311, .995415), tolerance = 5e-7)
  for (i in seq_len(nrow(fit$vertices))) m07_expect_absolute(sum(fit$vertices[i, ]), 1, tolerance = 1e-10)
  testthat::expect_error(m07_selection(weights = c(1, 0, 1, 1)))
  post <- m07_selection_posterior()
  m07_expect_absolute(post$posterior_mean, .789306, tolerance = 5e-7)
  m07_expect_absolute(post$posterior_variance, .00350740, tolerance = 5e-9)
  m07_expect_absolute(c(post$lower, post$upper), c(.658546, .888880), tolerance = 5e-7)
  testthat::expect_gt(abs(post$posterior_mean - post$transformed_mean_q), .004)
  # Independent gamma-draw benchmark of the ratio, distinct from Laplace integration.
  set.seed(771); G <- sapply(c(7, 13, 10, 4), function(shape) stats::rgamma(100000, shape))
  F <- (4 * G[, 1] + 2 * G[, 2]) / as.vector(G %*% c(4, 2, 1, 1))
  testthat::expect_lt(abs(mean(F) - post$posterior_mean), .001)
  testthat::expect_lt(abs(stats::var(F) - post$posterior_variance), .0001)
})
