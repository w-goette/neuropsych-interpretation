testthat::test_that("noisy-source confidence and physical posterior keep all nuisance inputs", {
  c <- m07_noisy_confidence(); m07_expect_absolute(c(c$lower, c$upper), c(3.756, 20.080), tolerance = 5e-4)
  fixed <- m07_noisy_confidence(include_case_uncertainty = FALSE)
  m07_expect_absolute(c(fixed$lower, fixed$upper), c(9.224, 14.131), tolerance = 5e-4)
  x <- m07_noisy(8192); y <- m07_noisy(8192, 2)
  testthat::expect_true(all(is.finite(unlist(x[c("mean", "variance", "lower", "upper")]))))
  testthat::expect_gt(x$physical_probability[1], .96); testthat::expect_lt(x$physical_probability[1], .975)
  testthat::expect_lt(max(abs(x$lower - y$lower)), .008)
  m07_expect_absolute(x$mean[2], x$mean[3])
  testthat::expect_gt(x$variance[3], x$variance[2])
  m07_expect_absolute(x$mean[2], 10.5487, tolerance = .002)
  testthat::expect_error(m07_noisy(1)); testthat::expect_error(m07_noisy(source_error_scale = -1))
})
