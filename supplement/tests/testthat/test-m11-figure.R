testthat::test_that("M11 figure retains two different probability operations", {
  d <- m11_figure_data()
  testthat::expect_equal(nrow(d$prevalence), 400)
  testthat::expect_equal(nrow(d$losses), 1203)
  testthat::expect_equal(d$readout$value[d$readout$quantity == "plugin_risk"], 8/17)
  testthat::expect_equal(d$readout$value[d$readout$quantity == "new_case_predictive"], 51/116)
  testthat::expect_equal(d$case_points$loss, c(4*51/116, 1-51/116, .2))
  testthat::expect_equal(length(unique(d$losses$action)), 3)
  testthat::expect_true(all(diff(d$prevalence$target_probability) > 0))
  p <- plot_m11_flag(d); gray <- plot_m11_flag(d, gray=TRUE)
  testthat::expect_equal(length(p), 2)
  testthat::expect_equal(length(gray), 2)
  built <- ggplot2::ggplot_build(p$losses)
  testthat::expect_equal(max(built$data[[2]]$y), 4)
  testthat::expect_equal(length(unique(built$data[[2]]$linetype)), 3)
  testthat::expect_equal(sort(built$data[[5]]$y), sort(d$case_points$loss))
})
