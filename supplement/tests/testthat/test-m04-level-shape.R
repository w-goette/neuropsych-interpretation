# Independent identities, defining-law checks and printed current-example targets.
m04_results <- m04_example_results()
testthat::test_that("geometry preserves metric and reconstructs the observed profile", {
  R <- matrix(c(1,.6,.6,1),2);x <- c(-1.5,0);v <- c(1,1)
  g <- m04_geometry(x,R,v)
  H <- matrix(c(2,0,.5,3),2)
  recoded <- m04_geometry(as.numeric(H%*%x),H%*%R%*%t(H),as.numeric(H%*%v))
  testthat::expect_equal(g,recoded,tolerance=1e-11)
  testthat::expect_equal(g$total,g$level^2+g$shape,tolerance=1e-12)
  testthat::expect_equal(m04_geometry(x,R,-2*v)$level,-g$level,tolerance=1e-12)
  testthat::expect_equal(m04_geometry(x,R,-2*v)$shape,g$shape,tolerance=1e-12)
  testthat::expect_equal(m04_results$profiles$shape,c(2.8125,0))
  testthat::expect_equal(m04_results$shifts$flat_retained_fraction,c(1,.2,0),tolerance=1e-12)
  testthat::expect_error(m04_geometry(x,matrix(1,2,2)),"positive definite")
  testthat::expect_error(m04_geometry(x,R,c(0,0)),"nonzero")
  testthat::expect_error(m04_geometry(x,R,c(1,NA)),"finite")
})
testthat::test_that("dispersion and its replication are statistics with separate laws", {
  R <- matrix(c(1,.6,.6,1),2);A <- diag(2)-matrix(.5,2,2)
  mom <- m04_quadratic_moments(c(0,0),R,A)
  testthat::expect_equal(mom$expectation,.4)
  testthat::expect_equal(mom$variance,.32)
  testthat::expect_equal(m04_quadratic_correlation(c(0,0),c(0,0),R,R,.6*R,A),.36)
  testthat::expect_equal(m04_quadratic_correlation(c(1,0),c(0,1),R,R,matrix(0,2,2),A),0)
  testthat::expect_error(m04_quadratic_correlation(c(0,0),c(0,0),R,R,2*R,A),"positive definite")
  testthat::expect_equal(m04_sd_correlation(c(0,1,-1)),c(0,1,1),tolerance=1e-12)
  testthat::expect_equal(m04_sd_correlation(.75),.5211743191703355,tolerance=1e-12)
  testthat::expect_equal(m04_sd_correlation(-.75),m04_sd_correlation(.75))
  testthat::expect_true(m04_sd_correlation(.75)<.75^2)
  testthat::expect_error(m04_sd_correlation(1.1),"Correlation")
  testthat::expect_lt(max(abs((m04_results$battery_length$squared_spread_correlation)-(c(.090433,.253029,.566450,.722037)))),5e-7)
})
testthat::test_that("exact confidence inversion preserves empty boundary behavior", {
  testthat::expect_true(m04_shape_confidence(0)$empty)
  ci <- m04_shape_confidence(2.8125)
  testthat::expect_equal(ci$lower,0)
  testthat::expect_equal(stats::pchisq(2.8125,1,ncp=ci$upper),.025,tolerance=1e-10)
  testthat::expect_error(m04_shape_confidence(-1),"nonnegative")
  x <- m04_results$displacement
  expected <- c(-.419263,.707107,-2.798489,1.121438,0,13.227871,1.203125,.002002,4.948484)
  testthat::expect_lt(max(abs((as.numeric(x[1,]))-(expected))),5e-7)
})
testthat::test_that("paired inference uses known zero means and the exact kernel", {
  testthat::expect_equal(m04_correlation_cdf(.3,12,0),stats::pbeta((.3+1)/2,5.5,5.5),tolerance=2e-9)
  testthat::expect_equal(m04_correlation_cdf(0,12,0),.5,tolerance=1e-10)
  testthat::expect_equal(m04_correlation_cdf(-1,12,.7),0)
  testthat::expect_equal(m04_correlation_cdf(1,12,.7),1)
  testthat::expect_error(m04_correlation_cdf(0,1,0),"a>1")
  z <- m04_results$paired
  testthat::expect_equal(m04_correlation_cdf(.75,12,z$rho_confidence_lower),.975,tolerance=1e-8)
  testthat::expect_equal(m04_correlation_cdf(.75,12,z$rho_confidence_upper),.025,tolerance=1e-8)
  testthat::expect_lt(max(abs((z$posterior_square_mean)-(.422317))),5e-7)
  testthat::expect_lt(max(abs((z$posterior_sd_mean)-(.388850))),5e-7)
  testthat::expect_lt(max(abs((c(z$square_credible_lower,z$square_credible_upper))-(c(.066395,.746008)))),5e-7)
  testthat::expect_lt(max(abs((c(z$sd_credible_lower,z$sd_credible_upper))-(c(.058489,.708639)))),5e-7)
  prior <- m04_results$prior_sensitivity
  testthat::expect_equal(prior$prior_mean_variance,c(2,10/9,1,1))
  testthat::expect_lt(max(abs((prior$posterior_square_mean)-(c(.422317,.191522,.482955,.206333)))),5e-7)
})
testthat::test_that("floors, scale and finite-reference comparisons preserve their experiment", {
  testthat::expect_equal(m04_results$floors$within_profile_variance,c(0,12.5,0,8,0,128/9,0))
  x <- c(4,-3,1);f <- -2
  testthat::expect_true(stats::var(pmax(f,x))<=stats::var(x))
  testthat::expect_equal(stats::var(x),sum(outer(x,x,"-")^2)/(2*3*2))
  testthat::expect_equal(unname(m04_results$coefficient_of_variation$raw_cov),c(.2495670992423109,0))
  testthat::expect_true(all(is.na(m04_results$coefficient_of_variation$standardized_cov)))
  testthat::expect_lt(max(abs((m04_results$finite_comparison$two_sided_tail)-(c(.093533,.118164,.092610)))),5e-7)
  p <- m04_results$power
  testthat::expect_lt(max(abs((p$flat_level)-(c(.299159,.138776,.05,.276751,.131669,.05)))),5e-7)
  testthat::expect_lt(max(abs((p$shape)-(c(.05,.200956,.608779,.05,.179268,.544335)))),5e-7)
  testthat::expect_lt(max(abs((p$full_radius)-(c(.155272,.184172,.503666,.133663,.156449,.418042)))),5e-7)
  testthat::expect_lt(max(abs((p$optimal_discriminant[1:3])-(c(.299159,.346475,.722812)))),5e-7)
  testthat::expect_true(all(is.na(p$optimal_discriminant[4:6])))
  testthat::expect_error(m04_power(c(-1,0),n=2),"n>2")
  testthat::expect_error(m04_power(c(-1,0),n=-Inf),"n>2")
})
testthat::test_that("training averages and realized-rule posterior agree with independent numerical targets", {
  z <- m04_results$training_average
  testthat::expect_lt(max(abs((as.numeric(z[1,]))-(c(.811620,.766904,.751941,.024053,1,1)))),5e-7)
  testthat::expect_true(z$estimated_covariance_training_average<z$oracle_auc)
  testthat::expect_true(z$known_covariance_training_average<z$oracle_auc)
  testthat::expect_error(m04_training_average(1.25,1,5),"group sizes")
  testthat::expect_error(m04_training_average(100),"stabilized")
  p <- m04_results$training_posterior
  testthat::expect_lt(max(abs((p$auc_posterior_mean)-(.796046))),5e-7)
  testthat::expect_lt(max(abs((c(p$auc_credible_lower,p$auc_posterior_median,p$auc_credible_upper))-(c(.502869,.818879,.965791)))),5e-7)
  testthat::expect_lt(max(abs((p$class1_probability)-(.392374))),5e-7)
  testthat::expect_equal(p$external_prevalence,.2)
})
