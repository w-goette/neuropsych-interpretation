  "B: A U-shaped curve gives the marginal difference rule's conditional null error versus fixed first score: 0.144 at 20, 0.064 at 35, 0.039 at 50. The dashed conditional innovation rule remains at 0.05."), file.path(output, "alt.txt"))
writeLines(c("Figure fig-m08-two-comparisons; synthetic known same-person normal law, means (50,52), covariance [[100,80],[80,100]], case (35,36). No fitting/simulation/seed.",
  "Same synthetic figure law as the chapter. Geometry/formulas are generated by the supplied R source; separate panels and shared tokens support small-screen reading.",
  paste("Raster device: ragg::agg_png; font:", book_font_family()),
  "Raster: each panel 4.8 x 5.2 inches, 180 dpi (864 x 936). Vector: 9.6 x 5.2 inch EPS, Helvetica.",
  "No ggplot2 extension: ordinary path, line, interval and point layers express the comparison; no fitted or inferential defaults added."), file.path(output, "PROVENANCE.txt"))
