argument <- grep("^--file=", commandArgs(FALSE), value = TRUE)
script <- sub("^--file=", "", argument[[1]])
if (!file.exists(script)) script <- gsub("~+~", " ", script, fixed = TRUE)
supplement_root <- dirname(dirname(dirname(normalizePath(script, mustWork = TRUE))))
project_library <- file.path(supplement_root, "renv", "library")
if (dir.exists(project_library)) .libPaths(c(project_library, .libPaths()))
options(neuropsychmethods.tokens = file.path(supplement_root, "inst/style/design-tokens.csv"))
source(file.path(supplement_root, "R/book-style.R"))
source(file.path(supplement_root, "R/m08-change.R"))
source(file.path(supplement_root, "R/m08-change-figure.R"))
output <- file.path(supplement_root, "outputs/m08-two-comparisons")
dir.create(output, recursive = TRUE, showWarnings = FALSE)
data <- m08_figure_data()
for (name in names(data)) readr::write_csv(data[[name]], file.path(output, paste0(name, ".csv")))
for (grayscale in c(FALSE, TRUE)) {
  suffix <- if (grayscale) "-grayscale" else ""
  plots <- m08_plots(data, grayscale)
  for (panel in names(plots)) ggplot2::ggsave(file.path(output, paste0("m08-panel-", panel, suffix, ".png")),
    plots[[panel]], device = ragg::agg_png, width = 4.8, height = 5.2, units = "in", dpi = 180, bg = "white")
}
# Vector composite retains a portable Helvetica master; raster uses actual
# shared available font. Identical font metrics across devices are not asserted.
plots <- m08_plots(data)
grDevices::postscript(file.path(output, "m08-two-comparisons.eps"), width = 9.6, height = 5.2,
  horizontal = FALSE, onefile = FALSE, paper = "special", family = "Helvetica")
grid::grid.newpage(); grid::pushViewport(grid::viewport(layout = grid::grid.layout(1, 2)))
for (i in 1:2) print(plots[[i]] + ggplot2::theme(text = ggplot2::element_text(family = "Helvetica")),
  vp = grid::viewport(layout.pos.row = 1, layout.pos.col = i), newpage = FALSE)
grDevices::dev.off()
