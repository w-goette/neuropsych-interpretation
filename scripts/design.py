#!/usr/bin/env python3
"""Compile shared CSV tokens to Quarto SCSS and check selected contrast pairs."""
from pathlib import Path
import argparse
import csv
import re

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / 'supplement/inst/style/design-tokens.csv'


def load_tokens(path=TOKENS):
    rows = list(csv.DictReader(path.open()))
    names = [r['name'] for r in rows]
    if len(names) != len(set(names)):
        raise ValueError('Duplicate design token names.')
    return {r['name']: r['value'] for r in rows}


def contrast(a, b):
    def luminance(color):
        if not re.fullmatch(r'#[0-9a-fA-F]{6}', color):
            raise ValueError(f'Expected six-digit hex color: {color}')
        values = [int(color[i:i+2], 16) / 255 for i in (1, 3, 5)]
        linear = [v/12.92 if v <= 0.04045 else ((v+0.055)/1.055)**2.4 for v in values]
        return sum(c*v for c, v in zip([0.2126, 0.7152, 0.0722], linear))
    l1, l2 = sorted([luminance(a), luminance(b)])
    return (l2 + 0.05) / (l1 + 0.05)


def compile_tokens(tokens):
    lines = ['// Generated by scripts/design.py from supplement/inst/style/design-tokens.csv.',
             '// Edit the CSV and regenerate; both Quarto and R use those tokens.', '/*-- scss:defaults --*/']
    for name, value in tokens.items():
        literal = f'"{value}"' if name.startswith('font_') else value
        lines.append(f'$book-{name.replace("_", "-")}: {literal};')
    return '\n'.join(lines) + '\n'


def check_contrast(tokens):
    results = []
    for mode in ['light', 'dark']:
        for text in ['text', 'muted', 'link', 'focus']:
            for surface in ['canvas', 'surface']:
                a, b = f'{text}_{mode}', f'{surface}_{mode}'
                ratio = contrast(tokens[a], tokens[b])
                if ratio < 4.5:
                    raise ValueError(f'{a}/{b}: {ratio:.2f}, below 4.5')
                results.append((a, b, ratio))
    for name in tokens:
        if name.startswith('plot_'):
            ratio = contrast(tokens[name], tokens['canvas_light'])
            if ratio < 3:
                raise ValueError(f'{name}/canvas_light: {ratio:.2f}, below plot-mark target 3')
            results.append((name, 'canvas_light', ratio))
    for name in ['focus_dark', 'accent_teal_dark', 'accent_purple_dark', 'accent_red_dark']:
        surface = 'brand_navy' if name == 'focus_dark' else 'surface_dark'
        ratio = contrast(tokens[name], tokens[surface])
        if ratio < 3:
            raise ValueError(f'{name}/{surface}: {ratio:.2f}, below component-mark target 3')
        results.append((name, surface, ratio))
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated SCSS is current; do not write it.')
    args = parser.parse_args()
    tokens = load_tokens()
    generated = compile_tokens(tokens)
    target = ROOT / 'book/styles/_tokens.scss'
    if args.check:
        if not target.exists() or target.read_text() != generated:
            parser.exit(1, 'Generated design tokens are stale. Run python3 scripts/design.py.\n')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(generated)
    for a, b, ratio in check_contrast(tokens):
        print(f'{a} / {b}: {ratio:.2f}:1')
    print('Token consistency and selected contrast pairs PASS.')


if __name__ == '__main__':
    main()
